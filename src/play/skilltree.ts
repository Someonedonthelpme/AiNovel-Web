/**
 * Build the tree.
 *
 * Six routes, four rings deep: a chain of minors out to a notable, with a
 * keystone on the rim. Deterministic in the seed and the background, so it is
 * never stored — it is regenerated identically wherever it is needed.
 */
export function skillTreeFor(seed: number, backgroundId: string, language: Lang = 'en'): SkillTree {
  const rng = mulberry32((seed ^ hash(backgroundId)) >>> 0);
  const words: WordBank = WORDS[language];
  const nodes: SkillNode[] = [];

  const start: SkillNode = {
    id: 'start',
    name: language === 'th' ? 'จุดเริ่ม' : 'Origin',
    description: language === 'th' ? 'จุดที่ทุกอย่างเริ่มต้น' : 'Where everything starts.',
    kind: 'minor',
    ring: 0,
    x: 50,
    y: 50,
    connections: [],
    grant: {},
  };
  nodes.push(start);

  for (let branch = 0; branch < BRANCHES; branch++) {
    // Each route leans on one ability, which is what gives it an identity.
    const ability = ABILITY_LIST[(branch + Math.floor(rng() * ABILITY_LIST.length)) % ABILITY_LIST.length];
    const angle = (branch / BRANCHES) * Math.PI * 2 + rng() * 0.25;
    let previous = start.id;

    for (let ring = 1; ring <= RINGS; ring++) {
      const radius = ring * 11;
      const wobble = (rng() - 0.5) * 0.18;
      const id = `b${branch}r${ring}`;
      const isKeystone = ring === RINGS;
      const isNotable = ring === RINGS - 1;
      const kind: NodeKind = isKeystone ? 'keystone' : isNotable ? 'notable' : 'minor';

      const node: SkillNode = {
        id,
        name: nameFor(rng, words, ability, kind),
        description: '',
        kind,
        ring,
        x: 50 + Math.cos(angle + wobble) * radius,
        y: 50 + Math.sin(angle + wobble) * radius,
        connections: [previous],
        grant: {},
      };

      if (kind === 'minor') {
        node.grant = rng() < 0.6 ? { ability: { [ability]: 1 } } : { maxHp: 3 };
      } else if (kind === 'notable') {
        node.grant = { ability: { [ability]: 1 }, ...(rng() < 0.5 ? { attack: 1 } : { ac: 1 }) };
      } else {
        // A keystone is a trade, not an upgrade. Without the cost, every build
        // converges on taking all of them.
        const trade = pick(rng, KEYSTONES);
        node.grant = trade.grant;
        node.cost = trade.cost;
        node.description = trade.note[language];
        // The rim is where the tree grows: these appear only once earned.
        node.requires = [{ kind: 'level', atLeast: 4 + branch }];
      }

      if (!node.description) node.description = describe(node.grant, node.cost, language);
      nodes.push(node);
      previous = id;
    }
  }

  // Cross-links, so routes join up and the tree is a graph rather than six
  // separate ladders — the point of contiguity is that paths can meet.
  for (let branch = 0; branch < BRANCHES; branch++) {
    const here = `b${branch}r2`;
    const next = `b${(branch + 1) % BRANCHES}r2`;
    const node = nodes.find((n) => n.id === here);
    if (node && rng() < 0.5) node.connections.push(next);
  }

  return { id: `tree_${backgroundId}`, start: start.id, nodes: linkBothWays(nodes) };
}

function nameFor(rng: Rng, words: WordBank, ability: Ability, kind: NodeKind): string {
  if (kind === 'keystone') return pick(rng, words.keystone);
  const base = pick(rng, words[ability]);
  if (kind === 'notable') return pick(rng, words.notable).replace('%s', base);
  return base;
}

function describe(grant: NodeGrant, cost: NodeGrant | undefined, language: Lang): string {
  const parts: string[] = [];
  for (const [ability, bonus] of Object.entries(grant.ability ?? {})) parts.push(`+${bonus} ${ability}`);
  if (grant.maxHp) parts.push(`+${grant.maxHp} hp`);
  if (grant.ac) parts.push(`+${grant.ac} armour`);
  if (grant.attack) parts.push(`+${grant.attack} to hit`);
  if (grant.damage) parts.push(`+${grant.damage} damage`);
  for (const [ability, penalty] of Object.entries(cost?.ability ?? {})) parts.push(`-${penalty} ${ability}`);
  if (cost?.maxHp) parts.push(`-${cost.maxHp} hp`);
  if (cost?.ac) parts.push(`-${cost.ac} armour`);
  if (cost?.attack) parts.push(`-${cost.attack} to hit`);
  if (cost?.damage) parts.push(`-${cost.damage} damage`);
  return parts.join(', ') || (language === 'th' ? 'ทางผ่าน' : 'a step along the way');
}

/** Edges are undirected; the generator writes only one side. */
function linkBothWays(nodes: SkillNode[]): SkillNode[] {
  const byId = new Map(nodes.map((n) => [n.id, { ...n, connections: [...n.connections] }]));
  for (const node of nodes) {
    for (const to of node.connections) {
      const other = byId.get(to);
      if (other && !other.connections.includes(node.id)) other.connections.push(node.id);
    }
  }
  return [...byId.values()];
}
