import type { Ability, Abilities } from '../combat/types.ts';
import { mulberry32 } from '../engine/roll.ts';
import type { Rng } from '../engine/roll.ts';
import type { TraitCondition } from './traits.ts';

/**
 * The passive tree.
 *
 * A Path of Exile-shaped skill system: one large graph, entered at a point
 * decided by your background, where a point may only be spent on a node
 * ADJACENT to one you already hold. That contiguity rule is what makes the tree
 * a set of routes rather than a shopping list — reaching a distant keystone
 * means paying for everything on the way, so a build is the path you took.
 *
 * The tree is GENERATED, not authored, and generated by code rather than by the
 * model: it is deterministic from the world seed and the background, so the
 * same character always gets the same tree, a replayed log allocates the same
 * nodes, and no model call is needed to draw it. A node granting whatever a
 * language model felt like would be unbalanceable.
 *
 * It is dynamic in one specific sense: some nodes are HIDDEN behind conditions
 * and do not exist on the map until you have done the thing. That is the seam
 * the Signet system will hang from.
 */

export const NODE_KINDS = ['minor', 'notable', 'keystone'] as const;
export type NodeKind = (typeof NODE_KINDS)[number];

export type NodeGrant = {
  ability?: Partial<Abilities>;
  maxHp?: number;
  ac?: number;
  /** Flat bonus to hit. */
  attack?: number;
  /** Flat bonus to damage. */
  damage?: number;
};

export type SkillNode = {
  id: string;
  name: string;
  description: string;
  kind: NodeKind;
  /** Rings out from the start. Drives both power and layout. */
  ring: number;
  x: number;
  y: number;
  connections: string[];
  grant: NodeGrant;
  /** Keystones give with one hand and take with the other. */
  cost?: NodeGrant;
  /**
   * Hidden until earned.
   *
   * A node with unmet requirements is not drawn at all — the dynamic half of
   * the tree, and where Signet gates will attach.
   */
  requires?: TraitCondition[];
};

export type SkillTree = {
  id: string;
  start: string;
  nodes: SkillNode[];
};

export type Lang = 'th' | 'en';

