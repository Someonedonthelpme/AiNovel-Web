/**
 * Names come from a word bank rather than a model call.
 *
 * A tree is fifty-odd nodes. Asking a model to name each one would cost a long
 * pause and a lot of tokens every time a character is made, and would not be
 * deterministic. Thai gets Thai words, so a Thai character does not read
 * English node names.
 */
